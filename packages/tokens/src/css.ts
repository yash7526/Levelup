import { colorRoles, colors, type ColorTheme, type ThemeName } from "./colors";
import { elevation, type ElevationName, toCssShadow } from "./elevation";
import { palette } from "./palette";
import { layout, motion, radii } from "./scales";
import { textStyles } from "./typography";

const PREFIX = "lu";

function kebab(value: string): string {
  return value.replace(/[A-Z]/g, (match) => `-${match.toLowerCase()}`);
}

function rem(px: number): string {
  return `${Number((px / 16).toFixed(4))}rem`;
}

function block(selector: string, declarations: string[]): string {
  return `${selector} {\n${declarations.map((line) => `  ${line}`).join("\n")}\n}`;
}

/** CSS custom property name for a semantic colour role, e.g. `--lu-color-surface-muted`. */
export function colorVar(role: (typeof colorRoles)[number]): string {
  return `--${PREFIX}-color-${kebab(role)}`;
}

function paletteDeclarations(): string[] {
  const lines = [`--color-white: ${palette.white};`, `--color-black: ${palette.black};`];
  for (const [name, value] of Object.entries(palette)) {
    if (typeof value === "string") continue;
    for (const [step, hex] of Object.entries(value)) {
      lines.push(`--color-${name}-${step}: ${hex};`);
    }
  }
  return lines;
}

function themeVariables(theme: ThemeName): string[] {
  const themeColors: ColorTheme = colors[theme];
  const lines = colorRoles.map((role) => `${colorVar(role)}: ${themeColors[role]};`);
  for (const [name, layers] of Object.entries(elevation[theme])) {
    lines.push(`--${PREFIX}-shadow-${name}: ${toCssShadow(layers)};`);
  }
  return [`color-scheme: ${theme};`, ...lines];
}

/**
 * Builds the stylesheet consumed by the web app (Tailwind CSS v4).
 *
 * - `@theme` registers static design tokens (palette, radii, type scale, easing).
 * - `@theme inline` maps semantic utilities (`bg-surface`, `text-foreground-muted`, …)
 *   to CSS variables, so a single class works in both themes.
 * - `:root` / `.dark` hold the per-theme values.
 */
export function createTokenStylesheet(): string {
  const staticTheme = [
    "--color-*: initial;",
    ...paletteDeclarations(),
    ...Object.entries(radii)
      .filter(([name]) => name !== "full")
      .map(([name, px]) => `--radius-${name}: ${px}px;`),
    ...Object.entries(textStyles).flatMap(([name, style]) => [
      `--text-${name}: ${rem(style.size)};`,
      `--text-${name}--line-height: ${rem(style.lineHeight)};`,
      `--text-${name}--letter-spacing: ${style.letterSpacing}em;`,
      `--text-${name}--font-weight: ${style.weight};`,
    ]),
    ...Object.entries(motion.easing).map(
      ([name, points]) => `--ease-${name}: cubic-bezier(${points.join(", ")});`,
    ),
  ];

  const semanticTheme = [
    ...colorRoles.map((role) => `--color-${kebab(role)}: var(${colorVar(role)});`),
    ...(Object.keys(elevation.light) as ElevationName[]).map(
      (name) => `--shadow-${name}: var(--${PREFIX}-shadow-${name});`,
    ),
  ];

  const layoutVariables = [
    ...Object.entries(layout).map(([name, px]) => `--${PREFIX}-${kebab(name)}: ${px}px;`),
    ...Object.entries(motion.duration).map(
      ([name, ms]) => `--${PREFIX}-duration-${name}: ${ms}ms;`,
    ),
    ...Object.entries(motion.easing).map(
      ([name, points]) => `--${PREFIX}-ease-${name}: cubic-bezier(${points.join(", ")});`,
    ),
  ];

  return [
    "/* AUTO-GENERATED by @levelup/tokens (pnpm --filter @levelup/tokens generate). Do not edit by hand. */",
    block("@theme", staticTheme),
    block("@theme inline", semanticTheme),
    block(":root", [...layoutVariables, ...themeVariables("light")]),
    block(".dark", themeVariables("dark")),
    "",
  ].join("\n\n");
}
